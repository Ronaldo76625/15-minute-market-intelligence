export function deviceLanguage(): Language {
  if (typeof navigator === "undefined") return "en";
  return navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
}

export function preferredLanguage(): Language {
  if (typeof localStorage === "undefined") return deviceLanguage();
  try {
    const saved = localStorage.getItem("kalshi-language");
    return saved === "en" || saved === "es" ? saved : deviceLanguage();
  } catch {
    return deviceLanguage();
  }
}

export function localizedMarketTitle(
  title: string,
  language: Language,
): string {
  if (language === "en") return title;
  const match = title.match(/^([A-Z0-9]+) price up in next 15 mins\?$/i);
  return match
    ? `¿Subirá el precio de ${match[1]} en los próximos 15 minutos?`
    : title;
}
